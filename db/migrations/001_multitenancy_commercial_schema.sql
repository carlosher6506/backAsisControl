ALTER TABLE public.ciclos_escolares ADD COLUMN IF NOT EXISTS team_id bigint
  REFERENCES public.teams(id) ON DELETE CASCADE;
ALTER TABLE public.niveles_academicos ADD COLUMN IF NOT EXISTS team_id bigint
  REFERENCES public.teams(id) ON DELETE CASCADE;
ALTER TABLE public.materias ADD COLUMN IF NOT EXISTS team_id bigint
  REFERENCES public.teams(id) ON DELETE CASCADE;
ALTER TABLE public.grupos ADD COLUMN IF NOT EXISTS team_id bigint
  REFERENCES public.teams(id) ON DELETE CASCADE;
ALTER TABLE public.alumnos ADD COLUMN IF NOT EXISTS team_id bigint
  REFERENCES public.teams(id) ON DELETE CASCADE;
ALTER TABLE public.configuraciones_evaluacion ADD COLUMN IF NOT EXISTS team_id bigint
  REFERENCES public.teams(id) ON DELETE CASCADE;
ALTER TABLE public.etiquetas ADD COLUMN IF NOT EXISTS team_id bigint
  REFERENCES public.teams(id) ON DELETE CASCADE;
ALTER TABLE public.tareas ADD COLUMN IF NOT EXISTS team_id bigint
  REFERENCES public.teams(id) ON DELETE CASCADE;
ALTER TABLE public.calificaciones ADD COLUMN IF NOT EXISTS team_id bigint
  REFERENCES public.teams(id) ON DELETE CASCADE;
ALTER TABLE public.grupo_materias ADD COLUMN IF NOT EXISTS team_id bigint
