-- Un grupo ya no pertenece a un maestro. Los maestros se asignan mediante
-- grupo_materias, permitiendo un solo "1° A" con muchas materias y docentes.
ALTER TABLE public.grupos ALTER COLUMN maestro_id DROP NOT NULL;
ALTER TABLE public.materias ALTER COLUMN maestro_id DROP NOT NULL;
ALTER TABLE public.grupos DROP CONSTRAINT IF EXISTS grupos_nivel_academico_ciclo_maestro_nombre_key;
CREATE UNIQUE INDEX IF NOT EXISTS grupos_team_nivel_ciclo_nombre_unico
  ON public.grupos (team_id, nivel_academico_id, ciclo_escolar_id, nombre)
  WHERE team_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS materias_team_nombre_unico
  ON public.materias (team_id, lower(nombre))
  WHERE team_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS alumnos_team_matricula_unica
  ON public.alumnos (team_id, matricula)
  WHERE team_id IS NOT NULL AND matricula IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_team_miembros_usuario ON public.team_miembros (usuario_id, activo);
CREATE INDEX IF NOT EXISTS idx_team_miembro_niveles_miembro ON public.team_miembro_niveles (team_miembro_id);
CREATE INDEX IF NOT EXISTS idx_invitaciones_team_codigo ON public.invitaciones_team (codigo) WHERE activo;
CREATE INDEX IF NOT EXISTS idx_suscripciones_team_estado ON public.suscripciones_team (team_id, estado);
CREATE INDEX IF NOT EXISTS idx_pagos_transferencia_estado ON public.pagos_transferencia (estado, created_at);
CREATE INDEX IF NOT EXISTS idx_grupos_team ON public.grupos (team_id);
CREATE INDEX IF NOT EXISTS idx_alumnos_team ON public.alumnos (team_id);
CREATE INDEX IF NOT EXISTS idx_grupo_materias_team ON public.grupo_materias (team_id);
CREATE INDEX IF NOT EXISTS idx_asistencia_sesiones_team ON public.asistencia_sesiones (team_id);

