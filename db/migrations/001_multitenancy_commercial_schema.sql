BEGIN;

-- ============================================================
-- 1. Equipos, membresías y alcance académico
-- ============================================================

CREATE TABLE IF NOT EXISTS public.teams (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_cuenta varchar(10) NOT NULL,
  nombre varchar(200) NOT NULL,
  nombre_escuela varchar(200),
  propietario_usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  email_contacto varchar(150),
  telefono varchar(30),
  direccion text,
  ciudad varchar(100),
  estado varchar(100),
  pais varchar(100) NOT NULL DEFAULT 'México',
  codigo_postal varchar(12),
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT teams_tipo_cuenta_check CHECK (tipo_cuenta IN ('personal', 'team')),
  CONSTRAINT teams_nombre_escuela_team_check CHECK (
    tipo_cuenta = 'personal' OR nombre_escuela IS NOT NULL
  )
);

-- Una cuenta Personal pertenece a una sola persona. El mismo usuario puede ser
-- director de uno o más teams empresariales si en el futuro se requiere.
CREATE UNIQUE INDEX IF NOT EXISTS teams_propietario_personal_unico
  ON public.teams (propietario_usuario_id)
  WHERE tipo_cuenta = 'personal';

CREATE TABLE IF NOT EXISTS public.team_miembros (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
  usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  rol varchar(20) NOT NULL,
  activo boolean NOT NULL DEFAULT true,
  invitado_por_usuario_id integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  joined_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT team_miembros_rol_check CHECK (rol IN ('director', 'subdirector', 'maestro')),
  CONSTRAINT team_miembros_team_usuario_unico UNIQUE (team_id, usuario_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS team_un_director_activo
  ON public.team_miembros (team_id)
  WHERE rol = 'director' AND activo;

-- El catálogo existente niveles_educativos sigue siendo global. Esta tabla indica
-- qué niveles ofrece cada escuela y permite configurarlos por team.
CREATE TABLE IF NOT EXISTS public.team_niveles_educativos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
  nivel_educativo_id integer NOT NULL REFERENCES public.niveles_educativos(id) ON DELETE RESTRICT,
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT team_niveles_educativos_unico UNIQUE (team_id, nivel_educativo_id)
);

-- Director ve todo su team sin filas aquí. Subdirector y maestro requieren una o
-- más filas para poder operar o consultar esos niveles.
CREATE TABLE IF NOT EXISTS public.team_miembro_niveles (
  team_miembro_id bigint NOT NULL REFERENCES public.team_miembros(id) ON DELETE CASCADE,
  team_nivel_educativo_id bigint NOT NULL REFERENCES public.team_niveles_educativos(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (team_miembro_id, team_nivel_educativo_id)
);

CREATE TABLE IF NOT EXISTS public.invitaciones_team (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
  codigo varchar(64) NOT NULL UNIQUE,
  rol varchar(20) NOT NULL,
  creado_por_usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  email_destino varchar(150),
  max_usos integer NOT NULL DEFAULT 1 CHECK (max_usos > 0),
  usos integer NOT NULL DEFAULT 0 CHECK (usos >= 0),
  expira_at timestamptz,
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT invitaciones_team_rol_check CHECK (rol IN ('subdirector', 'maestro')),
  CONSTRAINT invitaciones_team_usos_check CHECK (usos <= max_usos)
);

CREATE TABLE IF NOT EXISTS public.invitacion_team_niveles (
  invitacion_id bigint NOT NULL REFERENCES public.invitaciones_team(id) ON DELETE CASCADE,
  team_nivel_educativo_id bigint NOT NULL REFERENCES public.team_niveles_educativos(id) ON DELETE CASCADE,
  PRIMARY KEY (invitacion_id, team_nivel_educativo_id)
);

-- ============================================================
-- 2. Suscripciones, prueba, pagos por transferencia y términos
-- ============================================================

CREATE TABLE IF NOT EXISTS public.planes (
  codigo varchar(30) PRIMARY KEY,
  nombre varchar(100) NOT NULL,
  tipo_cuenta varchar(10) NOT NULL,
  precio_mensual numeric(10,2) NOT NULL CHECK (precio_mensual >= 0),
  max_alumnos integer,
  max_grupos integer,
  permite_qr boolean NOT NULL DEFAULT false,
  permite_exportar_concentrado boolean NOT NULL DEFAULT false,
  caracteristicas jsonb NOT NULL DEFAULT '{}'::jsonb,
  activo boolean NOT NULL DEFAULT true,
  CONSTRAINT planes_tipo_cuenta_check CHECK (tipo_cuenta IN ('personal', 'team')),
  CONSTRAINT planes_limites_check CHECK (
    (max_alumnos IS NULL OR max_alumnos > 0) AND
    (max_grupos IS NULL OR max_grupos > 0)
  )
);

INSERT INTO public.planes (
  codigo, nombre, tipo_cuenta, precio_mensual, max_alumnos, max_grupos,
  permite_qr, permite_exportar_concentrado, caracteristicas
) VALUES
  ('PERSONAL_PLATA', 'Personal Plata', 'personal', 150.00, 45, 3, false, false,
   '{"reportes": true, "asistencia_manual": true}'),
  ('PERSONAL_ORO', 'Personal Oro', 'personal', 250.00, NULL, NULL, true, true,
   '{"reportes": true, "asistencia_manual": true}'),
  ('TEAM', 'Team', 'team', 1000.00, NULL, NULL, true, true,
   '{"reportes": true, "asistencia_manual": true}')
ON CONFLICT (codigo) DO UPDATE SET
  nombre = EXCLUDED.nombre,
  precio_mensual = EXCLUDED.precio_mensual,
  max_alumnos = EXCLUDED.max_alumnos,
  max_grupos = EXCLUDED.max_grupos,
  permite_qr = EXCLUDED.permite_qr,
  permite_exportar_concentrado = EXCLUDED.permite_exportar_concentrado,
  caracteristicas = EXCLUDED.caracteristicas;

CREATE TABLE IF NOT EXISTS public.suscripciones_team (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
  plan_codigo varchar(30) NOT NULL REFERENCES public.planes(codigo),
  estado varchar(20) NOT NULL,
  inicio_prueba_at timestamptz,
  fin_prueba_at timestamptz,
  inicio_periodo_at timestamptz,
  fin_periodo_at timestamptz,
  tolerancia_hasta_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT suscripciones_team_estado_check CHECK (
    estado IN ('prueba', 'pendiente_pago', 'activa', 'tolerancia', 'suspendida', 'cancelada')
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS suscripcion_team_actual_unica
  ON public.suscripciones_team (team_id)
  WHERE estado IN ('prueba', 'pendiente_pago', 'activa', 'tolerancia');

CREATE TABLE IF NOT EXISTS public.pagos_transferencia (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  suscripcion_id bigint NOT NULL REFERENCES public.suscripciones_team(id) ON DELETE RESTRICT,
  monto numeric(10,2) NOT NULL CHECK (monto > 0),
  moneda char(3) NOT NULL DEFAULT 'MXN',
  referencia varchar(150),
  comprobante_url text NOT NULL,
  fecha_transferencia date,
  estado varchar(20) NOT NULL DEFAULT 'pendiente',
  enviado_por_usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  revisado_por_usuario_id integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  revisado_at timestamptz,
  nota_revision text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pagos_transferencia_estado_check CHECK (estado IN ('pendiente', 'aprobado', 'rechazado'))
);

CREATE TABLE IF NOT EXISTS public.aceptaciones_terminos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  version_terminos varchar(50) NOT NULL,
  aceptado_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ip inet,
  user_agent text,
  CONSTRAINT aceptaciones_terminos_unico UNIQUE (usuario_id, version_terminos)
);

-- ============================================================
-- 3. Pertenencia de los datos académicos al team
