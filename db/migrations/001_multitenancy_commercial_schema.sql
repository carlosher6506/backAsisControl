ALTER TABLE public.alumno_grupos ADD COLUMN IF NOT EXISTS team_id bigint
  REFERENCES public.teams(id) ON DELETE CASCADE;
ALTER TABLE public.asistencia_sesiones ADD COLUMN IF NOT EXISTS team_id bigint
  REFERENCES public.teams(id) ON DELETE CASCADE;
